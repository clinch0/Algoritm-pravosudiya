# -*- coding: utf-8 -*-
"""Генерация демо-документов приговоров (синтетические, без реальных персональных данных).

- приговор_пример_ok.docx     — юридически корректный приговор: ч. 2 ст. 158 УК РФ,
  пп. «и», «к» ч. 1 ст. 61 УК РФ, особый порядок (гл. 40 УПК РФ), лишение свободы
  1 год 6 месяцев условно (ст. 73 УК РФ), испытательный срок 2 года.
  Потолки: ч. 1 ст. 62 (2/3 от 5 = 3 г. 4 мес.) + ч. 5 ст. 62 (2/3 от 2/3 = 4/9 от 5 ≈ 2 г. 2,7 мес.);
  1 г. 6 мес. — с запасом ниже всех потолков. Испытательный срок при ЛС свыше 1 года —
  от 6 мес. до 5 лет (ч. 3 ст. 73 УК РФ).

- приговор_пример_ошибка.docx — намеренно ошибочный (для демонстрации работы системы):
  6 лет при максимуме 5 лет (превышение санкции), условное осуждение при опасном рецидиве
  (запрещено п. «в» ч. 1 ст. 73 УК РФ).
"""
from docx import Document
import os

BASE = os.path.dirname(os.path.abspath(__file__))

OK_TEXT = """
ПРИГОВОР
Именем Российской Федерации

15 марта 2026 года                                                           г. Москва

Ленинский районный суд г. Москвы в составе председательствующего судьи, при секретаре,
рассмотрев в открытом судебном заседании в особом порядке судебного разбирательства
(глава 40 УПК РФ) уголовное дело в отношении:

гражданина А., 12.05.1995 года рождения, ранее не судимого, работающего водителем,
обвиняемого в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,

УСТАНОВИЛ:
Подсудимый совершил кражу группой лиц по предварительному сговору с причинением
значительного ущерба гражданину.
Подсудимый вину признал полностью, в содеянном раскаялся, ходатайствовал о постановлении
приговора без проведения судебного разбирательства. Судом установлены смягчающие
обстоятельства: явка с повинной, активное способствование раскрытию и расследованию
преступления, добровольное возмещение имущественного ущерба, наличие малолетних детей.
Отягчающих обстоятельств не установлено.

ПРИГОВОРИЛ:
Признать гражданина А. виновным в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,
и назначить ему наказание в виде лишения свободы сроком на 1 год 6 месяцев.
На основании ст. 73 УК РФ назначенное наказание считать условным с испытательным сроком 2 года.
"""

BAD_TEXT = """
ПРИГОВОР
Именем Российской Федерации

20 марта 2026 года                                                           г. Подольск

Подольский городской суд, рассмотрев в открытом судебном заседании уголовное дело в отношении:

гражданина Б., ранее судимого, в действиях которого установлен опасный рецидив преступлений,
обвиняемого в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,

УСТАНОВИЛ:
Подсудимый совершил кражу с незаконным проникновением в помещение. Вину признал частично.
Смягчающих обстоятельств не установлено. Отягчающее обстоятельство: рецидив преступлений.

ПРИГОВОРИЛ:
Признать гражданина Б. виновным в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,
и назначить ему наказание в виде лишения свободы сроком на 6 лет.
На основании ст. 73 УК РФ назначенное наказание считать условным с испытательным сроком 4 года.
"""

ATTEMPT_TEXT = """
ПРИГОВОР
Именем Российской Федерации

10 марта 2026 года                                                           г. Москва

Ленинский районный суд г. Москвы, рассмотрев в открытом судебном заседании уголовное дело в отношении:

гражданина В., ранее не судимого,
обвиняемого в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,

УСТАНОВИЛ:
Подсудимый совершил покушение на кражу, то есть тайное хищение чужого имущества,
с незаконным проникновением в помещение, однако преступление не было доведено до конца
по не зависящим от него обстоятельствам.
Смягчающих и отягчающих обстоятельств не установлено.

ПРИГОВОРИЛ:
Признать гражданина В. виновным в совершении преступления, предусмотренного ч. 2 ст. 158 УК РФ,
и назначить ему наказание в виде лишения свободы сроком на 4 года.
"""

for name, text in [("приговор_пример_ok.docx", OK_TEXT), ("приговор_пример_ошибка.docx", BAD_TEXT),
                   ("приговор_пример_покушение.docx", ATTEMPT_TEXT)]:
    doc = Document()
    for para in text.strip().split("\n"):
        doc.add_paragraph(para)
    doc.save(os.path.join(BASE, name))
    print("saved", name)
