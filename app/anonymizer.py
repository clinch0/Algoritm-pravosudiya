# ------------------------------------------------------- правила замены
# Порядок важен: сначала форматы с разделителями (их нельзя спутать с голыми
# цифрами), в конце — ИНН (10/12 цифр подряд) и эвристика ФИО.
_PATTERNS: list[tuple[str, str]] = [
    # email: user@domain.ru
    (r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", "EMAIL"),
    # СНИЛС: 123-456-789 01
    (r"(?<!\d)\d{3}-\d{3}-\d{3}\s\d{2}(?!\d)", "СНИЛС"),
    # паспорт: «серия 1234 номер 567890», «серия 1234 № 567890»
    (r"[Сс]ерия\s+\d{4}\s+(?:№\s*)?(?:[Нн]омер\s+)?\d{6}", "ПАСПОРТ"),
    # паспорт: «паспорт 1234 567890», «паспорт серии 1234 № 567890»
    (r"[Пп]аспорт[а]?(?:\s+(?:РФ|гражданина(?:\s+РФ)?))?\s+(?:сери[яи]\s+)?\d{4}\s*(?:№\s*)?\d{6}", "ПАСПОРТ"),
    # телефон: +7 900 123-45-67, 8 (495) 123-45-67, 8-916-123-45-67, 89161234567
    (r"(?<!\d)(?:\+7|8)[\s-]?\(?\d{3}\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}(?!\d)", "ТЕЛЕФОН"),
    # адрес: г. Москва, ул. Ленина, д. 1, кв. 2 (город + 1-4 элемента)
    (r"(?:г\.|гор\.|город|пос\.|пгт\.?|с\.|село|дер\.|деревня)\s+"
     r"[А-ЯЁ][а-яёА-ЯЁ\-]{0,40}"
     r"(?:\s*,?\s*(?:ул\.|улиц[аы]|пр-т|проспект[а]?|пер\.|переул(?:ок|ка)"
     r"|б-р|бульвар[а]?|наб\.|набережн[а-я]+|ш\.|шоссе"
     r"|д\.|дом[а]?|стр\.|строение|корп\.|корпус|кв\.|квартир[аы]"
     r"|пом\.|помещение|оф\.|офис)\s*[^,.;]{1,25}){1,4}", "АДРЕС"),
    # дата цифрами: 12.03.1990 / 12.3.1990
    (r"(?<!\d)\d{1,2}\.\d{1,2}\.\d{4}(?!\d)", "ДАТА"),
    # дата прописью: «5 марта 1990 года» / «5 марта 1990 г.»
    (r"(?<!\d)\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля"
     r"|августа|сентября|октября|ноября|декабря)\s+\d{4}"
     r"(?:\s+(?:года|г\.)(?!\w))?", "ДАТА"),
    # ИНН: 10 или 12 цифр подряд (сначала 12, чтобы не откусить от 12-значного)
    (r"(?<!\d)(?:\d{12}|\d{10})(?!\d)", "ИНН"),
]

# -------------------------------------------------- эвристика ФИО
# Кандидат: 1-3 слова с заглавной буквы (возможен дефис) + необязательные
# инициалы (Иванов И.И.). Только в середине предложения: перед пробелом —
# строчная буква или знак препинания, но НЕ точка (начало предложения и
# сокращения вида «г. Москва» не трогаем).
_NAME_RE = re.compile(
    r"(?<=[а-яё,;:»\)\]\(«])\s+"
    r"([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?"
    r"(?:\s+[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?){0,2}"
    r"(?:\s+[А-ЯЁ]\.[А-ЯЁ]?\.?)?)"
)


def _apply_patterns(text: str) -> tuple[str, dict]:
    """Применяет все правила и возвращает (текст, счётчики замен)."""
    counters = {key: 0 for key in TOKENS}

    def _mask_names(match: re.Match) -> str:
        """Маскирует слова-кандидаты, кроме терминов из белого списка.

        Несколько слов одного имени схлопываются в один токен <ФИО>,
        а юридические термины внутри фразы сохраняются как есть.
        """
        phrase = match.group(1)
        words = phrase.split()
        pieces = []
        added = 0
        for word in words:
            clean = word.strip(".,;:()«»\"'")
            if clean.lower() in _LEGAL_TERMS:
                pieces.append(word)          # термин — не трогаем
            else:
                if not pieces or pieces[-1] != TOKENS["ФИО"]:
                    pieces.append(TOKENS["ФИО"])
                    counters["ФИО"] += 1
                    added += 1
        if added == 0:
            return match.group(0)            # вся фраза — терминология
        # сохраняем ведущий пробел из совпадения
        leading = match.group(0)[: len(match.group(0)) - len(phrase)]
        return leading + " ".join(pieces)

    for pattern, key in _PATTERNS:
        def _repl(m: re.Match, key: str = key) -> str:
            counters[key] += 1
            return TOKENS[key]

        text = re.sub(pattern, _repl, text)

    def full_name(m):
        phrase = m.group(0)
        if any(w.lower().strip(".") in _LEGAL_TERMS for w in phrase.split()):
            return phrase
        counters["ФИО"] += 1
        return TOKENS["ФИО"]

    text = re.sub(r"\b[А-ЯЁ]\.\s*[А-ЯЁ]\.\s*[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?", full_name, text)
    text = re.sub(r"\b[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+(?:вич|вна|ич|чна)\b", full_name, text)
    text = re.sub(r"(?m)(?<![а-яёА-ЯЁ])[А-ЯЁ][а-яё]+\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.", full_name, text)
    # эвристика ФИО — последним шагом, по уже очищенному тексту
    text = _NAME_RE.sub(_mask_names, text)
    return text, counters


def mask_text(text: str) -> str:
    """Возвращает текст, в котором персональные данные заменены токенами.

    Пример:
        mask_text("Осуждённый Иванов Пётр Сергеевич, 12.03.1990 г.р.")
        -> "Осуждённый <ФИО>, <ДАТА> г.р."
    """
    if not text:
        return ""
    masked, _ = _apply_patterns(str(text))
    return masked


def anonymization_report(text: str) -> dict:
    """Считает, сколько сущностей каждого типа было заменено (для аудита).

    Возвращает словарь вида:
        {"ФИО": 2, "ДАТА": 1, "АДРЕС": 0, ..., "total": 3}
    Ключ "total" — суммарное число замен.
    """
    _, counters = _apply_patterns(str(text or ""))
    report = {key: counters[key] for key in TOKENS}
    report["total"] = sum(counters.values())
    return report


